package basic;

public class ArithmeticOperator {
    public static void main(String[] args) {

        int a = 15;
        int b = 4;

        // 덧셈
        System.out.println("a + b = " + (a + b));

        // 뺄셈
        System.out.println("a - b = " + (a - b));

        // 곱셈
        System.out.println("a * b = " + (a * b));

        // 나눗셈
        System.out.println("a / b = " + (a / b));

        // 나머지
        System.out.println("a % b = " + (a % b));

//        // 예상 출력:
//        덧셈 결과: 19
//        뺄셈 결과: 11
//        곱셈 결과: 60
//        나눗셈 결과: 3
//        나머지 결과: 3
    }
}
